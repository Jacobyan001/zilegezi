const CJK_RE = /[\u3400-\u9fff\uf900-\ufaff]/;

function toChars(s: string): string[] {
  return Array.from(s).filter((c) => CJK_RE.test(c));
}

/** 构建去重后的分年级字表（一个字只归入它最早出现的年级） */
function buildPools(): Record<GradeId, string[]> {
  const seen = new Set<string>();
  const result = {} as Record<GradeId, string[]>;
  for (const g of GRADES) {
    const list: string[] = [];
    for (const ch of toChars(RAW[g.id])) {
      if (!seen.has(ch)) {
        seen.add(ch);
        list.push(ch);
      }
    }
    result[g.id] = list;
  }
  return result;
}

export const CHAR_POOLS: Record<GradeId, string[]> = buildPools();

/** 从某年级起最多跨 n 个年级的合并字表（用于难度进阶"出现下一个年级的字"） */
export function poolFrom(grade: GradeId, extraGrades = 0): string[] {
  const startIdx = GRADES.findIndex((g) => g.id === grade);
  const endIdx = Math.min(GRADES.length - 1, startIdx + extraGrades);
  const out: string[] = [];
  for (let i = startIdx; i <= endIdx; i++) out.push(...CHAR_POOLS[GRADES[i].id]);
  return out;
}

